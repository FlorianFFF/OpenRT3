"""Which rewritten functions have been checked against the original.

Merges the coverage files that tools/simcheck.py writes with --coverage=<file>
(one per save/scenario: 1 when the original function ran in that run) and
adds the functions whose original ran during the difftests. Writes
docs/simcheck_coverage.txt (addr name runs) and docs/coverage.md.

    python tools/coverage.py [--difftest=<difftest.coverage>[,<difftest_leaves.coverage>]] <coverage file> [...]
"""
import re
import sys
from pathlib import Path

from replacements import REPLACEMENT_RE

ROOT = Path(__file__).resolve().parents[1]


def main():
    files = [Path(a) for a in sys.argv[1:] if not a.startswith("--")]
    # --difftest=a[,b]: difftest.coverage and difftest_leaves.coverage (the leaf
    # test runs in its own process)
    dts = [Path(f) for a in sys.argv if a.startswith("--difftest=") for f in a[11:].split(",") if f]
    if not files:
        print(__doc__)
        return 1
    size = {}
    for line in (ROOT / "decomp" / "index.tsv").read_text().splitlines():
        a, _, s, *_ = line.split("\t")
        size[int(a, 16)] = int(s)
    where, name = {}, {}
    for p in sorted((ROOT / "src").rglob("*.cpp")):
        for m in REPLACEMENT_RE.finditer(p.read_text(encoding="utf-8")):
            a = int(m.group(1), 16)
            where.setdefault(a, p.relative_to(ROOT / "src").as_posix())
            name.setdefault(a, m.group(2))
    runs = {a: 0 for a in where}
    for f in files:
        for line in f.read_text().splitlines():
            a, _, n = line.split()
            a = int(a, 16)
            if a in runs and int(n) > 0:
                runs[a] += 1
    tested = set()
    # Every function in the leaf test's table is called and compared there
    # (tests/test_leaves.cpp); its run needs no coverage probes (which clash
    # with that test's own exception handling).
    leaf_table = ROOT / "tests" / "test_leaves_table.cpp"
    if leaf_table.exists():
        import re
        tested |= {int(a, 16) for a in re.findall(r"\{ 0x([0-9a-f]+), \"", leaf_table.read_text())}
    for dt in dts:
        for line in dt.read_text().splitlines():
            a, _, n = line.split()
            if int(n) > 0:
                tested.add(int(a, 16))

    (ROOT / "docs" / "simcheck_coverage.txt").write_text(
        "".join(f"{a:08x} {name[a]} {runs[a]}\n" for a in sorted(runs)))

    def pct(x, y):
        return f"{x} / {y} ({100 * x / y:.1f}%)" if y else "0 / 0"

    allf = sorted(runs)
    ran = [a for a in allf if runs[a]]
    either = [a for a in allf if runs[a] or a in tested]
    bytes_ = lambda fs: sum(size.get(a, 0) for a in fs)
    out = ["# Verification coverage", "",
           "Generated by `tools/coverage.py` from the runs listed below (simcheck and two-player",
           "checks; the files are kept in `out/coverage_runs/`) and the leaf test's table.",
           "*Ran* = the original function ran in at least one simcheck run, whose",
           "rewrite then produced the same saved game. *Difftest* = the original",
           "function ran during the difftests (`build.bat test` with",
           "RT3RE_COVERAGE set), inside a test that compared it, or a caller,",
           "with the rewrite. Neither = only checked by reading.", "",
           "Runs: " + ", ".join(f"`{f.stem}`" for f in files), "",
           "| | Functions | Code bytes |", "|---|---|---|",
           f"| Ran in simcheck | {pct(len(ran), len(allf))} | {pct(bytes_(ran), bytes_(allf))} |",
           f"| Ran or difftest | {pct(len(either), len(allf))} | {pct(bytes_(either), bytes_(allf))} |",
           "", "## Per source file", "",
           "| File | Ran | Ran or difftest | Unchecked bytes |", "|---|---|---|---|"]
    byfile = {}
    for a in allf:
        byfile.setdefault(where[a], []).append(a)
    for f, fs in sorted(byfile.items(), key=lambda kv: -bytes_([a for a in kv[1] if not runs[a] and a not in tested])):
        r = [a for a in fs if runs[a]]
        e = [a for a in fs if runs[a] or a in tested]
        un = bytes_([a for a in fs if a not in e])
        out.append(f"| {f} | {len(r)}/{len(fs)} | {len(e)}/{len(fs)} | {un} |")
    # Why a function cannot be run against the original (docs/unchecked_reasons.txt:
    # "<addr> <name>: <reason>" lines; # comments).
    reasons = {}
    rpath = ROOT / "docs" / "unchecked_reasons.txt"
    if rpath.exists():
        for line in rpath.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.startswith("#"):
                head, _, why = line.partition(":")
                reasons[int(head.split()[0], 16)] = why.strip()
    un = sorted((a for a in allf if not runs[a] and a not in tested), key=lambda a: (where[a], a))
    unexplained = [a for a in un if a not in reasons]
    out += ["", "## Unchecked functions", ""]
    if not un:
        out += ["None: every rewritten function ran against the original in a simcheck run, a",
                "two-player check, the leaf test or a difftest."]
    else:
        out += [f"{len(un)} rewritten functions ({bytes_(un)} bytes) never ran in a check. The reason each",
                "cannot be run against the original is in `docs/unchecked_reasons.txt`"
                + (f"; {len(unexplained)} have none yet." if unexplained else "."), "",
                "| Address | Function | File | Bytes | Reason |", "|---|---|---|---|---|"]
        out += [f"| {a:06x} | {name[a]} | {where[a]} | {size.get(a, 0)} | {reasons.get(a, '(none yet)')} |" for a in un]
    # Functions only a difftest ran: what a game check still has to reach, by kind.
    notrun = [a for a in allf if not runs[a] and a in tested]
    if notrun:
        kinds = [
            ("network flows two-player checks do not set up yet (internet lobby, map transfer, votes, resync)",
             r"^(Net|NetMsg|Lobby|Peer|Msg|MpDialog|MpScenarioList|GameList|Merger|MergerWindow|Session|Slots|WorkerA)_"),
            ("windows, dialogs and their callbacks in states no script reaches yet",
             r"(Window|Dialog|Editor|Picker|Tooltip|Widget|List|View|Panel|Screen|EditBox|TreeView|Dropdown|Hover|Draw|Cb)"),
            ("files, devices, textures, sound and the registry",
             r"^(Render|Engine|Texture|Sound|File|Stream|StreamB|RegKey|Save|Rle|Image|Font|Shell|Fatal|Movie|Video|Cursor|Heap)"),
        ]
        groups = {k: [] for k, _ in kinds}
        groups["game logic in situations the saves do not contain"] = []
        for a in notrun:
            k = next((k for k, rx in kinds if re.search(rx, name[a])), "game logic in situations the saves do not contain")
            groups[k].append(a)
        out += ["", "## Not run in a game yet", "",
                f"{len(notrun)} functions ran only in difftests (against the original there), not yet in a",
                "game check (`docs/simcheck_coverage.txt` lists them with 0 runs):", ""]
        out += [f"- {len(v)}: {k}" for k, v in groups.items() if v]
    stale = sorted(a for a in reasons if a in runs and (runs[a] or a in tested))
    if stale:  # a reason for a function that now ran: the reason can go
        out += ["", "Listed in `docs/unchecked_reasons.txt` but checked now: "
                + ", ".join(f"{a:06x} {name[a]}" for a in stale) + "."]
    (ROOT / "docs" / "coverage.md").write_text("\n".join(out) + "\n")
    print(f"ran {len(ran)}/{len(allf)}, ran or difftest {len(either)}/{len(allf)}, "
          f"bytes {bytes_(either)}/{bytes_(allf)}; unchecked {len(un)}, without a reason {len(unexplained)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
