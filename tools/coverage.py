"""Which rewritten functions have been checked against the original.

Merges the coverage files that tools/simcheck.py writes with --coverage=<file>
(one per save/scenario: 1 when the original function ran in that run) and
adds the functions whose original ran during the difftests. Writes
docs/simcheck_coverage.txt (addr name runs) and docs/coverage.md.

    python tools/coverage.py [--difftest=<difftest.coverage>[,<difftest_leaves.coverage>]] <coverage file> [...]
"""
import sys
from pathlib import Path

from replacements import REPLACEMENT_RE

ROOT = Path(__file__).resolve().parents[1]


def main():
    files = [Path(a) for a in sys.argv[1:] if not a.startswith("--")]
    # --difftest=a[,b]: difftest.coverage and difftest_leaves.coverage (the leaf
    # test runs in its own process)
    dts = [Path(f) for a in sys.argv if a.startswith("--difftest=") for f in a[11:].split(",") if f]
    if not files:
        print(__doc__)
        return 1
    size = {}
    for line in (ROOT / "decomp" / "index.tsv").read_text().splitlines():
        a, _, s, *_ = line.split("\t")
        size[int(a, 16)] = int(s)
    where, name = {}, {}
    for p in sorted((ROOT / "src").rglob("*.cpp")):
        for m in REPLACEMENT_RE.finditer(p.read_text(encoding="utf-8")):
            a = int(m.group(1), 16)
            where.setdefault(a, p.relative_to(ROOT / "src").as_posix())
            name.setdefault(a, m.group(2))
    runs = {a: 0 for a in where}
    for f in files:
        for line in f.read_text().splitlines():
            a, _, n = line.split()
            a = int(a, 16)
            if a in runs and int(n) > 0:
                runs[a] += 1
    tested = set()
    for dt in dts:
        for line in dt.read_text().splitlines():
            a, _, n = line.split()
            if int(n) > 0:
                tested.add(int(a, 16))

    (ROOT / "docs" / "simcheck_coverage.txt").write_text(
        "".join(f"{a:08x} {name[a]} {runs[a]}\n" for a in sorted(runs)))

    def pct(x, y):
        return f"{x} / {y} ({100 * x / y:.1f}%)" if y else "0 / 0"

    allf = sorted(runs)
    ran = [a for a in allf if runs[a]]
    either = [a for a in allf if runs[a] or a in tested]
    bytes_ = lambda fs: sum(size.get(a, 0) for a in fs)
    out = ["# Verification coverage", "",
           "Generated by `tools/coverage.py` from the simcheck runs listed below.",
           "*Ran* = the original function ran in at least one simcheck run, whose",
           "rewrite then produced the same saved game. *Difftest* = the original",
           "function ran during the difftests (`build.bat test` with",
           "RT3RE_COVERAGE set), inside a test that compared it, or a caller,",
           "with the rewrite. Neither = only checked by reading.", "",
           "Runs: " + ", ".join(f"`{f.stem}`" for f in files), "",
           "| | Functions | Code bytes |", "|---|---|---|",
           f"| Ran in simcheck | {pct(len(ran), len(allf))} | {pct(bytes_(ran), bytes_(allf))} |",
           f"| Ran or difftest | {pct(len(either), len(allf))} | {pct(bytes_(either), bytes_(allf))} |",
           "", "## Per source file", "",
           "| File | Ran | Ran or difftest | Unchecked bytes |", "|---|---|---|---|"]
    byfile = {}
    for a in allf:
        byfile.setdefault(where[a], []).append(a)
    for f, fs in sorted(byfile.items(), key=lambda kv: -bytes_([a for a in kv[1] if not runs[a] and a not in tested])):
        r = [a for a in fs if runs[a]]
        e = [a for a in fs if runs[a] or a in tested]
        un = bytes_([a for a in fs if a not in e])
        out.append(f"| {f} | {len(r)}/{len(fs)} | {len(e)}/{len(fs)} | {un} |")
    out += ["", "## Largest unchecked functions", "", "| Address | Function | File | Bytes |", "|---|---|---|---|"]
    un = sorted((a for a in allf if not runs[a] and a not in tested), key=lambda a: -size.get(a, 0))
    out += [f"| {a:06x} | {name[a]} | {where[a]} | {size.get(a, 0)} |" for a in un[:60]]
    (ROOT / "docs" / "coverage.md").write_text("\n".join(out) + "\n")
    print(f"ran {len(ran)}/{len(allf)}, ran or difftest {len(either)}/{len(allf)}, "
          f"bytes {bytes_(either)}/{bytes_(allf)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
