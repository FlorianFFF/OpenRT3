"""Generates src/game/builtin_strings.inc from builtin_strings.tsv, the dump
of the original BuiltinString (0x5193f0) made by tests/dump_tables.cpp.

Output: per language a sorted {id, text} table. IDs absent from a table
return the empty string (0x5c87a8 in the exe).
"""
import collections
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / "Railroad Tycoon 3 Full Game" / "builtin_strings.tsv"
OUT = ROOT / "src" / "game" / "builtin_strings.inc"
EMPTY = "005c87a8"
SPECIAL = {"005c9ce8", "005d2170"}  # id 1 early return; id 7 fallback pointer
LANGS = [0, 1, 2, 3, 4, 8, 10]  # 6/11/12 use table 0; others have no built-ins


def cstr(b):
    out = []
    for c in b:
        if 0x20 <= c < 0x7f and c not in (0x22, 0x5c, 0x3f):
            out.append(chr(c))
        else:
            out.append(f"\\x{c:02x}\"\"")  # close/reopen so hex escapes never swallow digits
    return '"' + "".join(out) + '"'


def main():
    by = collections.defaultdict(dict)
    for line in SRC.read_text().splitlines():
        lang, ident, ptr, hexs = line.split("\t")
        by[int(lang)][int(ident)] = (ptr, bytes.fromhex(hexs))
    lines = ["// Generated by tools/gen_builtin_strings.py from the original 0x5193f0. Do not edit.", ""]
    names = []
    for lang in LANGS:
        entries = sorted((i, s) for i, (p, s) in by[lang].items() if p != EMPTY and p not in SPECIAL)
        name = f"kBuiltin{lang}"
        names.append((name, len(entries)))
        lines.append(f"static const BuiltinString {name}[] = {{")
        for i, s in entries:
            lines.append(f"    {{ {i}, {cstr(s)} }},")
        if not entries:
            lines.append("    { 0, nullptr },")
        lines.append("};")
        lines.append("")
    lines.append("// Indexed by language (0x6d3c84); 6/11/12 share table 0.")
    lines.append("static const BuiltinTable kBuiltinTables[13] = {")
    table = dict(zip(LANGS, names))
    for lang in range(13):
        src = 0 if lang in (6, 11, 12) else lang
        if src in table:
            lines.append(f"    {{ {table[src][0]}, {table[src][1]} }}, // {lang}")
        else:
            lines.append(f"    {{ nullptr, 0 }}, // {lang}")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {OUT} ({sum(n for _, n in names)} entries)")


if __name__ == "__main__":
    main()
