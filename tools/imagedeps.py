"""What the rewrite still takes from the original exe image.

    python tools/imagedeps.py [--list=calls|data|globals]

Scans src/ for the three kinds of use of the game's image and writes
docs/imagedeps.md:
- calls to code at an exe address (a cast of an address literal to a function,
  hook::Orig, a "call" in inline asm), split into calls of functions the
  rewrite has itself (RT3_REPLACE: these can become direct calls) and calls of
  code it does not have (the C runtime, D3DX 8, the GameSpy SDK, imports);
- reads of data at an exe address (constants D()/Fl()/..., tables, strings);
- the game's globals (src/core/globals.h, hook::Global).
"""
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

from replacements import REPLACEMENT_RE

ROOT = Path(__file__).resolve().parents[1]
BANDS = [(0x401000, 0x56c850, "game"), (0x56c850, 0x58bc30, "D3DX 8"), (0x58bc30, 0x5a1000, "GameSpy SDK"),
         (0x5a1000, 0x5b9000, "C runtime"), (0x5b9000, 0x5c0000, "imports")]

ADDR = r"0x(?:4|5)[0-9a-fA-F]{5}"
CALL_RES = [
    re.compile(r"\)\s*\(?\s*(" + ADDR + r")\s*\)?\s*\)\s*\("),          # ((T(*)(...))0x4.....)(
    re.compile(r"hook::Orig<[^>]*>\s*\(\s*(" + ADDR + r")\s*\)"),          # hook::Orig<T>(0x4.....)
    re.compile(r"mov\s+eax\s*,\s*(" + ADDR + r")\s*\n\s*call\s+eax", re.I),  # inline asm
    re.compile(r"\bcall\s+(?:dword ptr\s*)?\[?\s*(" + ADDR + r")", re.I),
]
DATA_RE = re.compile(r"\b(?:D|Fl|F_?\w*|Fl_\d+|D\w*|BoatF|BoatD|RowD)\s*\(\s*(0x(?:5|6)[0-9a-fA-F]{5})\s*\)|"
                     r"\(\s*const\s+[\w\s\*]+\*\s*\)\s*(0x(?:5|6)[0-9a-fA-F]{5})")
RDATA_RE = re.compile(r"\bRdata\s*\(\s*(0x[0-9a-fA-F]{6})\s*\)")
ACC_DEF_RE = re.compile(r"\b(\w+)\s*\((?:uint32_t|uintptr_t|unsigned) \w+\)\s*\{\s*return \*\s*\(const [\w ]+\*\)\s*rt3::Rdata\(")
RDATA_START, RDATA_END = 0x5c8000, 0x5ecadc  # the exe's .rdata section


def in_rdata(a):
    return RDATA_START <= a < RDATA_END


GLOBAL_RE =re.compile(r"#define\s+(g_\w+)\s+\(::hook::Global<[^>]*>\((0x[0-9a-fA-F]+)\)\)")


def band(a):
    return next((n for lo, hi, n in BANDS if lo <= a < hi), "data")


def main():
    have = set()
    for p in (ROOT / "src").rglob("*.cpp"):
        have |= {int(m.group(1), 16) for m in REPLACEMENT_RE.finditer(p.read_text(encoding="utf-8", errors="replace"))}
    calls_own, calls_lib, data, own = Counter(), Counter(), Counter(), Counter()
    where_lib = defaultdict(set)
    for p in sorted((ROOT / "src").rglob("*.cpp")):
        if p.name in ("harness.cpp", "drawtrace.cpp") or "launcher" in p.parts:
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        seen = set()
        for rx in CALL_RES:
            for m in rx.finditer(text):
                a = int(m.group(1), 16)
                key = (m.start(1), a)
                if key in seen:
                    continue
                seen.add(key)
                if a in have:
                    calls_own[a] += 1
                else:
                    calls_lib[a] += 1
                    where_lib[a].add(p.name)
        # Accessors of this file that read through rt3::Rdata (the rewrite's own
        # copy of .rdata, src/core/rdata.cpp): their .rdata reads are not image reads.
        own_acc = set(ACC_DEF_RE.findall(text))
        for m in RDATA_RE.finditer(text):
            a = int(m.group(1), 16)
            (own if in_rdata(a) else data)[a] += 1
        for m in DATA_RE.finditer(text):
            a = int(m.group(1) or m.group(2), 16)
            name = re.match(r"\w+", m.group(0)).group(0) if m.group(1) else None
            (own if name in own_acc and in_rdata(a) else data)[a] += 1
    globs = GLOBAL_RE.findall((ROOT / "src" / "core" / "globals.h").read_text(encoding="utf-8"))
    libband = Counter()
    for a, n in calls_lib.items():
        libband[band(a)] += n
    lines = ["# What the rewrite still takes from the exe image", "",
             "Generated by `tools/imagedeps.py` (src/ without the test harness and the launchers).", "",
             "| Use | Places | Distinct addresses |", "|---|---|---|",
             f"| Calls of rewritten functions by exe address (can become direct calls) | {sum(calls_own.values())} | {len(calls_own)} |",
             f"| Calls of code the rewrite does not have | {sum(calls_lib.values())} | {len(calls_lib)} |",
             f"| Reads of constants, tables and strings in the image | {sum(data.values())} | {len(data)} |",
             f"| Reads of .rdata constants from the rewrite's own copy (src/core/rdata.cpp) | {sum(own.values())} | {len(own)} |",
             f"| Game globals at their exe addresses (src/core/globals.h) | | {len(globs)} |", "",
             "Calls of code the rewrite does not have, by part of the exe:", "",
             "| Part | Places | Distinct |", "|---|---|---|"]
    for b in ("game", "D3DX 8", "GameSpy SDK", "C runtime", "imports", "data"):
        d = [a for a in calls_lib if band(a) == b]
        if d:
            lines.append(f"| {b} | {libband[b]} | {len(d)} |")
    game_missing = sorted(a for a in calls_lib if band(a) == "game")
    if game_missing:
        lines += ["", "Game-band addresses called but not rewritten (mid-function entries, thunks, data):", "",
                  ", ".join(f"{a:06x} ({'/'.join(sorted(where_lib[a]))})" for a in game_missing)]
    (ROOT / "docs" / "imagedeps.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[6:10]))
    lst = next((a[7:] for a in sys.argv if a.startswith("--list=")), None)
    if lst == "calls":
        for a, n in sorted(calls_own.items()):
            print(f"own {a:06x} {n}")
        for a, n in sorted(calls_lib.items()):
            print(f"lib {a:06x} {n} {band(a)} {'/'.join(sorted(where_lib[a]))}")
    elif lst == "data":
        for a, n in sorted(data.items()):
            print(f"{a:06x} {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
