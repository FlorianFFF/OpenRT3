"""Rewrite progress: which original functions have a replacement.

Reads decomp/index.tsv (all functions) and every RT3_REPLACE(0x..., ...) in
src/, then writes docs/progress.md with totals per band and per 64 KB block.

Bands (from function alignment and library signatures):
  game     0x401000-0x56c84f  the game's own code (16-byte aligned)  -> rewrite
  d3dx     0x56c850-0x58bc2f  statically linked D3DX8 (unaligned)    -> replace with a library
  imports  0x58bc30-0x58bc8f  import thunks
  gamespy  0x58bc90-0x5a0fff  GameSpy SDK compiled into the game      -> rewrite
  crt      0x5a1000-          MSVC 2003 C runtime                     -> standard CRT
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BANDS = [("game", 0x401000, 0x56c850), ("d3dx", 0x56c850, 0x58bc30),
         ("imports", 0x58bc30, 0x58bc90), ("gamespy", 0x58bc90, 0x5a1000),
         ("crt", 0x5a1000, 0x10000000)]


def is_lib(name):
    return not re.match(r"(thunk_)?FUN_", name)


def band(a):
    for name, lo, hi in BANDS:
        if lo <= a < hi:
            return name
    return "?"


def main():
    funcs = {}
    for line in (ROOT / "decomp" / "index.tsv").read_text().splitlines():
        addr, name, size, *_ = line.split("\t")
        funcs[int(addr, 16)] = (name, int(size))
    done = {}
    for p in (ROOT / "src").rglob("*.cpp"):
        for m in re.finditer(r"RT3_REPLACE\(\s*0x([0-9a-fA-F]+)\s*,\s*(\w+)", p.read_text(encoding="utf-8")):
            done[int(m.group(1), 16)] = (m.group(2), p.relative_to(ROOT).as_posix())

    unknown = sorted(a for a in done if a not in funcs)
    out = ["# Rewrite progress", "",
           "Generated by `tools/progress.py`. Size = bytes of original machine code.", "",
           "| Band | Functions done | Code bytes done |", "|---|---|---|"]
    for name, lo, hi in BANDS:
        fs = [a for a in funcs if lo <= a < hi and not (name == "game" and is_lib(funcs[a][0]))]
        if not fs:
            continue
        n_done = sum(1 for a in fs if a in done)
        b_all = sum(funcs[a][1] for a in fs)
        b_done = sum(funcs[a][1] for a in fs if a in done)
        out.append(f"| {name} | {n_done} / {len(fs)} ({100 * n_done / len(fs):.1f}%) | "
                   f"{b_done} / {b_all} ({100 * b_done / max(b_all, 1):.1f}%) |")
    out += ["", "## Game code by 64 KB block", "", "| Block | Done | Total |", "|---|---|---|"]
    for blk in range(0x40, 0x57):
        fs = [a for a in funcs if a >> 16 == blk and band(a) == "game" and not is_lib(funcs[a][0])]
        if fs:
            out.append(f"| 0x{blk:02x}xxxx | {sum(1 for a in fs if a in done)} | {len(fs)} |")
    out += ["", "## Replaced functions", "", "| Address | Rewrite | File |", "|---|---|---|"]
    for a in sorted(done):
        out.append(f"| 0x{a:06x} | {done[a][0]} | {done[a][1]} |")
    if unknown:
        out += ["", "**Not a function start in the index:** " + ", ".join(f"0x{a:x}" for a in unknown)]
    (ROOT / "docs" / "progress.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[4:4 + len(BANDS) + 1]))
    if unknown:
        print("WARNING not function starts:", [hex(a) for a in unknown])


if __name__ == "__main__":
    main()
