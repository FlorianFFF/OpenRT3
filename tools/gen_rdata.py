"""The rewrite's own copy of the game's read-only data (build step).

    python tools/gen_rdata.py [<out file>]     (default out/gen/rdata.inc)

Copies the .rdata section of the user's RT3.exe 1.06 (tools/pe.py find_exe:
the constants, tables and strings at 0x5c8000..) into a C initializer that
src/core/rdata.cpp compiles into rt3re.dll, so the rewrite reads its constants
from its own data instead of the exe image (rt3::Rdata, src/hook/hook.h). The
file is generated from the user's copy of the game at build time and is not
part of the repository. It is rewritten only when its contents change.
"""
import struct
import sys
from pathlib import Path

from pe import find_exe

ROOT = Path(__file__).resolve().parents[1]


def rdata(exe):
    b = Path(exe).read_bytes()
    pe = struct.unpack_from("<I", b, 0x3C)[0]
    count = struct.unpack_from("<H", b, pe + 6)[0]
    opt = struct.unpack_from("<H", b, pe + 20)[0]
    base = struct.unpack_from("<I", b, pe + 52)[0]
    for i in range(count):
        s = pe + 24 + opt + i * 40
        if b[s:s + 8].rstrip(b"\0") == b".rdata":
            vsize, va, rsize, raw = struct.unpack_from("<IIII", b, s + 8)
            data = b[raw:raw + min(vsize, rsize)]
            return base + va, data + bytes(vsize - len(data))
    raise ValueError("no .rdata section in %s" % exe)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "out" / "gen" / "rdata.inc"
    start, data = rdata(find_exe())
    lines = [f"// Generated by tools/gen_rdata.py from the game's RT3.exe: its .rdata section.",
             f"#define RT3_RDATA_START 0x{start:x}u",
             f"#define RT3_RDATA_SIZE 0x{len(data):x}u",
             'extern "C" alignas(16) const unsigned char g_rt3Rdata[RT3_RDATA_SIZE] = {']
    for i in range(0, len(data), 32):
        lines.append(",".join(str(c) for c in data[i:i + 32]) + ",")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
